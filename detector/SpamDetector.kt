    /**
     * تشخیص دستهٔ یک پیامک. کاملاً آفلاین و بی‌طرف‌دار نسبت به وضعیت برنامه.
     * @param sender شماره یا نام فرستنده (هر قالبی: 0912..., +98912..., Bank Melli, 500019000)
     * @param body متن پیام
     */
    fun detect(sender: String, body: String): SmsDetection {
        val n = low(body)
        if (n.isEmpty()) {
            val probs = SmsCategory.values().associateWith { 0.0 }.toMutableMap()
            probs[SmsCategory.NOTIFICATION] = 1.0
            return SmsDetection(SmsCategory.NOTIFICATION, 1.0, probs, SmsDetection.Decider.EMPTY, listOf("متن خالی"), 0)
        }
        val num = FloatArray(NUM_FEATURES)
        numFeatures(sender, body, num)
        val (idx, vals) = docVector(sender, body, num)
        val probs = softmax(scores(idx, vals, W_NUM, W_TOK))

        val risk = riskScoreOf(sender, body)
        val rule = ruleOverride(sender, body, 0, risk)
        val cats = SmsCategory.values()
        val finalProbs = HashMap<SmsCategory, Double>(8)
        if (rule != null) {
            val c = cats.indexOf(rule.cat)
            for (i in cats.indices) finalProbs[cats[i]] = probs[i] * (1.0 - rule.conf)
            finalProbs[rule.cat] = (finalProbs[rule.cat] ?: 0.0) + rule.conf
            return SmsDetection(rule.cat, rule.conf, finalProbs, SmsDetection.Decider.RULE, rule.why, risk)
        }
        var best = 0
        for (i in probs.indices) if (probs[i] > probs[best]) best = i
        for (i in cats.indices) finalProbs[cats[i]] = probs[i]
        return SmsDetection(cats[best], probs[best], finalProbs, SmsDetection.Decider.MODEL, describe(cats[best], num), risk)
    }

    /** توضیح کوتاه فارسی برای تصمیم مدل */
    private fun describe(cat: SmsCategory, num: FloatArray): List<String> {
        val why = ArrayList<String>(3)
        when (cat) {
            SmsCategory.OTP -> why.add("الگوی کد یکبارمصرف")
            SmsCategory.BANKING -> {
                if (num[36] > 0f) why.add("ورود به سامانه بانک")
                if (num[28] > 0f || num[38] > 0f) why.add("واژه‌های تراکنش بانکی")
                if (num[4] > 0f) why.add("فرستنده بانکی")
            }
            SmsCategory.NOTIFICATION -> {
                if (num[27] > 0f) why.add("واژه‌های اطلاع‌رسانی")
                if (num[57] > 0f) why.add("سفارش/رهگیری")
            }
            SmsCategory.PROMOTION -> {
                if (num[22] > 0f) why.add("واژه‌های تبلیغاتی")
                if (num[8] > 0f) why.add("لغو اشتراک انبوه")
                if (num[6] > 0f) why.add("دارای لینک")
            }
            SmsCategory.SPAM -> why.add("ساختار مشکوک")
            SmsCategory.CONTACTS -> why.add("متن شخصی بدون نشانه تبلیغ/خدمات")
        }
        return why
    }

