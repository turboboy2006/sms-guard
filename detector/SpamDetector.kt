    private fun tokenize(n: String): List<String> {
        val t = RX_NON_TOKEN.replace(RX_DIGITS.replace(n, " {n} "), " ").trim()
        if (t.isEmpty()) return emptyList()
        val toks = t.split(' ').filter { it == "{n}" || it.length >= 2 }
        if (toks.isEmpty()) return emptyList()
        val out = ArrayList<String>(toks.size * 2)
        out.addAll(toks)
        for (i in 0 until toks.size - 1) out.add(toks[i] + "_" + toks[i + 1])
        return out
    }

    private fun senderTokens(addr: String): List<String> {
        val a = Regex("[^\\p{L}\\p{N}]+").replace(low(addr), " ").trim()
        if (a.isEmpty()) return emptyList()
        return a.split(' ').filter { it.length >= 3 }.map { "s:$it" }
    }

    private fun docVector(addr: String, body: String, num: FloatArray): Pair<IntArray, FloatArray> {
        val idx = ArrayList<Int>(64)
        val vals = ArrayList<Float>(64)
        for (i in 0 until NUM_FEATURES) if (num[i] != 0f) { idx.add(i); vals.add(num[i]) }
        val seen = HashSet<String>()
        for (t in tokenize(low(body))) {
            val j = TOKEN_INDEX[t] ?: continue
            if (!seen.add(t)) continue
            idx.add(NUM_FEATURES + j); vals.add(1f)
        }
        for (t in senderTokens(addr)) {
            val j = TOKEN_INDEX[t] ?: continue
            if (!seen.add(t)) continue
            idx.add(NUM_FEATURES + j); vals.add(1f)
        }
        return Pair(idx.toIntArray(), vals.toFloatArray())
    }

    private fun scores(idx: IntArray, vals: FloatArray, wNum: Array<FloatArray>, wTok: Array<FloatArray>): DoubleArray {
        val k = wNum.size
        val z = DoubleArray(k)
        for (c in 0 until k) {
            val nk = wNum[c]
            val tk = wTok[c]
            var s = 0.0
            for (p in idx.indices) {
                val f = idx[p]
                s += vals[p] * (if (f < NUM_FEATURES) nk[f] else tk[f - NUM_FEATURES])
            }
            z[c] = s
        }
        return z
    }

    private fun softmax(z: DoubleArray): DoubleArray {
        var mx = Double.NEGATIVE_INFINITY
        for (v in z) if (v > mx) mx = v
        var sum = 0.0
        val p = DoubleArray(z.size)
        for (i in z.indices) { p[i] = Math.exp(z[i] - mx); sum += p[i] }
        if (sum <= 0.0) { for (i in p.indices) p[i] = 1.0 / p.size; return p }
        for (i in p.indices) p[i] /= sum
        return p
    }

