        var worst = 0.0
        for (c in CASES) {
            val r = detect(c.sender, c.body)
            var maxDiff = 0.0
            for (cat in SmsCategory.values()) {
                val want = c.probs[cat.ordinal].toDouble()
                val got = r.probabilities[cat] ?: 0.0
                val d = Math.abs(want - got)
                if (d > maxDiff) maxDiff = d
            }
            if (maxDiff > worst) worst = maxDiff
            val okCat = r.category.fa == c.expect
            val okProb = maxDiff <= 0.02
            if (!okCat || !okProb) {
                fail++
                if (verbose) println("FAIL  ${c.note}: انتظار=${c.expect} گرفت=${r.category.fa} اختلاف‌احتمال=${"%.4f".format(maxDiff)}")
            }
        }
        if (verbose) {
            println("self-test: ${CASES.size - fail}/${CASES.size} موفق   بیشترین اختلاف احتمال=${"%.4f".format(worst)}")
        }
        return fail
    }

    /* ======================= رابط خط فرمان ======================= */
    @JvmStatic
    fun main(args: Array<String>) {
        if (args.isNotEmpty() && (args[0] == "--self-test" || args[0] == "-t")) {
            val fail = selfTest()
            exitProcess(if (fail == 0) 0 else 1)
        }
        if (args.isNotEmpty() && args[0] == "--help") {
            println("ورودی: هر خط  «فرستنده<TAB>متن پیام»  — خروجی: دسته، اطمینان، احتمال‌ها")
            println("گزینه‌ها: --self-test | --help")
            return
        }
        val out = StringBuilder()
        while (true) {
            val line = readLine() ?: break
            if (line.isBlank()) continue
            val tab = line.indexOf('\t')
            val sender: String
            val body: String
            if (tab >= 0) { sender = line.substring(0, tab).trim(); body = line.substring(tab + 1).trim() }
            else { sender = ""; body = line.trim() }
            val r = detect(sender, body)
            out.setLength(0)
            out.append(r.category.fa).append('\t')
            out.append("%.3f".format(r.confidence)).append('\t')
            out.append(r.decidedBy.name).append('\t')
            out.append("risk=").append(r.riskScore).append('\t')
            for (cat in SmsCategory.values()) out.append(cat.name).append('=').append("%.3f".format(r.probabilities[cat] ?: 0.0)).append(' ')
            if (r.reasons.isNotEmpty()) out.append('\t').append(r.reasons.joinToString(" · "))
            println(out.toString())
        }
    }
