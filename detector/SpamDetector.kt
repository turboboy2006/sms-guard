        val ipLink = links.any { RX_IP_LINK.containsMatchIn(it) }
        val puny = links.any { it.contains("xn--") }
        val riskyTld = links.any { l -> RISKY_TLD.any { l.lowercase().contains(it) } }
        val shortener = links.any { l -> SHORTENER.any { l.lowercase().contains(it) } }
        val brandMismatch = links.isNotEmpty() && BRANDS.any { (b, doms) ->
            n.contains(low(b)) && links.none { l -> doms.any { d -> l.lowercase().contains(d) } }
        }
        val fraudGate = brandMismatch || riskyTld || ipLink || puny || (!knownBrand && (links.isNotEmpty() || s.isBulk))
        val fraudWords = ArrayList<String>()
        if (strongFraud.isNotEmpty() && fraudGate) fraudWords.addAll(strongFraud)
        if (weakActive) fraudWords.addAll(weakFraud)
        val brandPhish = brandMismatch && (riskyTld || shortener || fraudWords.isNotEmpty() ||
            Regex("(بانک|bank|رمز|کارت|شبا)").containsMatchIn(n))
        val isFraud = fraudWords.isNotEmpty() || card || sheba || ipLink || puny || brandPhish

        val promoHits = hitsWord(n, PROMO)
        val notifyHits = hitsWord(n, NOTIFY)
        val optOut = RX_OPT_OUT.containsMatchIn(body)

        if (otp && !isFraud) return Rule(SmsCategory.OTP, 0.93, listOf("کد/رمز با بافت ورود یا احراز هویت"), score)
        if (bank && links.isEmpty() && !card && !sheba) {
            val why = ArrayList<String>()
            if (s.bankName) why.add("فرستنده بانکی")
            if (bankTxn) why.add("متن تراکنش/موجودی")
            if (bankLogin) why.add("ورود به سامانه بانک")
            return Rule(SmsCategory.BANKING, 0.90, why, score)
        }
        if (isFraud) {
            val why = ArrayList<String>(fraudWords.take(2))
            if (card) why.add("شماره کارت")
            if (sheba) why.add("شبا")
            if (ipLink) why.add("لینک IP")
            if (puny) why.add("دامنه هوموگراف")
            if (brandPhish) why.add("جعل نام برند")
            return Rule(SmsCategory.SPAM, 0.88, why.take(3), score)
        }
        if (score >= 45 && !optOut && !knownBrand && notifyHits.isEmpty()) {
            return Rule(SmsCategory.SPAM, 0.70, listOf("تبلیغ ناخواسته بدون لغو اشتراک"), score)
        }
        if (bank) {
            val why = ArrayList<String>()
            if (s.bankName) why.add("فرستنده بانکی")
            if (bankTxn) why.add("متن تراکنش")
            if (bankLogin) why.add("ورود به سامانه بانک")
            return Rule(SmsCategory.BANKING, 0.80, why, score)
        }
        return null
    }

    /** امتیاز خطر ۰..۱۰۰ و سیگنال‌های متنی */
    private fun riskScoreOf(sender: String, body: String): Int {
        val n = low(body)
        val s = senderOf(sender)
        val links = RX_LINK.findAll(body).map { it.value }.toList()
        var score = 0
        if (links.isNotEmpty()) score += 22
        score += minOf(30, 16 * hitsWord(n, PROMO).size)
        if (hasWord(n, URGENT)) score += 14
        if (hasWord(n, CTA)) score += 16
        if (hasWord(n, MONEY_LURE)) score += 20
        if (RX_OPT_OUT.containsMatchIn(body)) score += 8
        if (s.isBulk) score += 8
        if (hitsWord(n, FRAUD_STRONG).isNotEmpty()) score += 45
        if (RX_CARD16.containsMatchIn(RX_DASH_SPACE.replace(n, "")) && n.contains("کارت")) score += 40
        if (RX_SHEBA.containsMatchIn(RX_DASH_SPACE.replace(n, ""))) score += 40
        if (links.any { RX_IP_LINK.containsMatchIn(it) }) score += 40
        if (links.any { it.contains("xn--") }) score += 35
        if (links.any { l -> RISKY_TLD.any { l.lowercase().contains(it) } }) score += 18
        if (links.any { l -> SHORTENER.any { l.lowercase().contains(it) } }) score += 12
        if (links.isNotEmpty() && BRANDS.any { (b, doms) ->
                n.contains(low(b)) && links.none { l -> doms.any { d -> l.lowercase().contains(d) } }
            }) score += 20
        var emoji = 0
        var ci = 0
        while (ci < body.length) {
            val cp = Character.codePointAt(body, ci)
            ci += Character.charCount(cp)
            if ((cp in 0x1F300..0x1FAFF) || (cp in 0x2600..0x27BF)) emoji++
        }
        if (RISKY_EMOJI.count { body.contains(it) } >= 2) score += 16 else if (emoji >= 5) score += 8
        return maxOf(0, minOf(100, score))
    }

