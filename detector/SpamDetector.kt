    /** یکسان‌سازی عربی→فارسی، ارقام، نیم‌فاصله و فاصله‌های اضافه */
    fun normalize(input: CharSequence): String {
        val sb = StringBuilder(input.length + 8)
        var i = 0
        while (i < input.length) {
            val cp = Character.codePointAt(input, i)
            i += Character.charCount(cp)
            when (cp) {
                0x064A, 0x0649 -> sb.append('\u06CC')      // ي , ى → ی
                0x0643 -> sb.append('\u06A9')               // ك → ک
                0x06C0, 0x0629 -> sb.append('\u0647')       // ۀ , ة → ه
                0x0623, 0x0625, 0x0622 -> sb.append('\u0627')
                else -> sb.appendCodePoint(cp)
            }
        }
        var s = RX_HARAKAT.replace(sb.toString(), "")
        s = RX_ZERO_WIDTH.replace(s, "")
        s = RX_PERSIAN_DIGITS.replace(s) { ((it.value[0].code - 0x06F0) + 48).toChar().toString() }
        s = RX_ARABIC_DIGITS.replace(s) { ((it.value[0].code - 0x0660) + 48).toChar().toString() }
        s = s.replace('\u200C', ' ').replace('\u00A0', ' ')
        return RX_WS.replace(s, " ").trim()
    }

