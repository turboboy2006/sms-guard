/** شش دستهٔ تشخیص */
enum class SmsCategory(val fa: String) {
    CONTACTS("مخاطبین/شخصی"),
    BANKING("بانکی"),
    OTP("OTP/رمز پویا"),
    NOTIFICATION("اطلاع‌رسانی"),
    PROMOTION("تبلیغاتی"),
    SPAM("اسپم");

    companion object {
        fun fromFa(fa: String): SmsCategory? = values().firstOrNull { it.fa == fa }
    }
}

/** نتیجهٔ تشخیص یک پیام */
data class SmsDetection(
    val category: SmsCategory,
    /** احتمال دستهٔ انتخاب‌شده (۰..۱) */
    val confidence: Double,
    /** توزیع احتمال روی هر شش دسته */
    val probabilities: Map<SmsCategory, Double>,
    /** تصمیم با قاعده گرفته شده یا مدل آماری */
    val decidedBy: Decider,
    /** دلایل فارسی (برای نمایش به کاربر) */
    val reasons: List<String>,
    /** امتیاز خطر ۰..۱۰۰ */
    val riskScore: Int,
) {
    enum class Decider { RULE, MODEL, EMPTY }

    val isSpam: Boolean get() = category == SmsCategory.SPAM
    /** تبلیغاتی یا اسپم: نامه‌های ناخواسته */
    val isUnwanted: Boolean get() = category == SmsCategory.SPAM || category == SmsCategory.PROMOTION
}

